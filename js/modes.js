function orderGame(root, E, done) {
  const sorted = [...E].sort((a, b) => a.y - b.y); let pool, placed, miss;
  const start = () => { pool = shuf(E); placed = []; miss = 0; draw(''); };
  function draw(msg) {
    root.innerHTML = `${bar(root, 'رتّب العلماء من الأقدم ميلاداً إلى الأحدث', `الأخطاء <b>${AR(miss)}</b>`)}
      <div class="tl">${sorted.map((e, k) => { const p = placed[k]; return `<div class="slot ${p ? 'f' : ''}"><em>${AR(k + 1)}</em>${p ? `${p.t}<span style="margin-inline-start:auto;color:var(--gold-t)">نحو ${AR(p.y)}م</span>` : ''}</div>`; }).join('')}</div>
      <div class="pool">${pool.map((e, k) => `<button class="chip" data-k="${k}">${e.t}</button>`).join('')}</div><div class="fb">${msg}</div>`;
    $$('.chip', root).forEach(b => b.onclick = () => {
      const e = pool[+b.dataset.k];
      if (e === sorted[placed.length]) { placed.push(e); pool.splice(+b.dataset.k, 1); if (placed.length === E.length) return done(Math.max(0, E.length - miss), E.length, start); draw('صحيح!'); }
      else { miss++; draw('ليس الآن. من وُلد قبل الباقين؟'); }
    });
  }
  start();
}

