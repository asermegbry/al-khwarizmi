/* مطابقة: اضغط عنصراً من عمود ثم ما يناسبه من العمود الآخر. mk() ترجع [{k, a, b}] */
function matchGame(root, mk, done) {
  let sel, hits, miss, n, pairs;
  const start = () => {
    pairs = mk(); n = pairs.length; hits = 0; miss = 0; sel = null;
    const col = (side, arr) => `<div>${shuf(arr).map(p => `<button class="mi" data-s="${side}" data-k="${p.k}">${p[side]}</button>`).join('')}</div>`;
    root.innerHTML = `${bar(root, 'اضغط على عنصر ثم على ما يناسبه', `الأخطاء <b>${AR(0)}</b>`)}<div class="mt">${col('a', pairs)}${col('b', pairs)}</div><div class="fb"></div>`;
    $$('.mi', root).forEach(b => b.onclick = () => {
      if (b.classList.contains('done')) return;
      if (!sel) { sel = b; b.classList.add('on'); return; }
      if (sel === b) { b.classList.remove('on'); sel = null; return; }
      if (sel.dataset.s === b.dataset.s) { sel.classList.remove('on'); sel = b; b.classList.add('on'); return; }
      sel.classList.remove('on');
      if (sel.dataset.k === b.dataset.k) {
        sel.classList.add('done'); b.classList.add('done'); $('.fb', root).textContent = 'صحيح!';
        if (++hits === n) setTimeout(() => done(Math.max(0, n - miss), n, start), 700);
      } else {
        miss++; $('.bar span:last-child b', root).textContent = AR(miss); $('.fb', root).textContent = 'ليس هذا الزوج، جرّب مرة أخرى.';
        const x = sel; [x, b].forEach(e => e.classList.add('no')); setTimeout(() => [x, b].forEach(e => e.classList.remove('no')), 450);
      }
      sel = null;
    });
  };
  start();
}

