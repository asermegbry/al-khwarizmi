function fin(root, sc, tot, again, back, backT, kid, meta) {
  const p = sc / tot, st = p === 1 ? 3 : p >= .6 ? 2 : p > 0 ? 1 : 0;
  if (kid) STAR.add(st);
  if (meta && meta.save) meta.save(sc, tot);
  if (kid && meta && meta.sid && p >= .6 && KS.add('kh-stk', meta.sid)) setTimeout(() => toast(`ملصق جديد! حصلتَ على ملصق ${byId(meta.sid).name}`), 600);
  const msg = p === 1 ? 'ممتاز! علامة كاملة.' : p >= .6 ? 'أحسنت! نتيجة جيدة.' : 'حاول مرة أخرى، ستتحسن.';
  const big = kid ? `<div class="big stars">${'★'.repeat(st)}<span>${'★'.repeat(3 - st)}</span></div><p>${AR(sc)} من ${AR(tot)}${st ? ` — ربحتَ ${AR(st)} ${st > 2 ? 'نجوم' : st === 2 ? 'نجمتين' : 'نجمة'}` : ''}</p>` : `<div class="big">${AR(sc)} / ${AR(tot)}</div>`;
  root.innerHTML = `<div class="end"><h2>${msg}</h2>${big}<p style="margin-top:18px"><button class="btn" id="again">مرة أخرى</button> <a class="btn alt" href="${back}">${backT}</a></p></div>`;
  $('#again').onclick = again;
  if (p >= .6) confetti(root);
}

